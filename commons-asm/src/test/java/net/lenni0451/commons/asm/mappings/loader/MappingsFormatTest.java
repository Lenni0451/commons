package net.lenni0451.commons.asm.mappings.loader;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

class MappingsFormatTest {

    @Test
    void testProguard() {
        assertEquals(MappingsFormat.PROGUARD, detect("com.foo.Bar -> a.b.c:", "    int field -> a"));
    }

    @Test
    void testRetroguard() {
        assertEquals(MappingsFormat.RETROGUARD, detect(".class_map a b", ".field_map a/c d"));
    }

    @Test
    void testSrg() {
        assertEquals(MappingsFormat.SRG, detect("PK: . x", "CL: a b", "FD: a/c x/d"));
    }

    @Test
    void testTsrgV1() {
        assertEquals(MappingsFormat.TSRG_V1, detect("a b", "\tc d"));
    }

    @Test
    void testTsrgV1Header() {
        assertEquals(MappingsFormat.TSRG_V1, detect("tsrg left right", "a b", "\tc d"));
        //Classes named 'tsrg', 'tsrg2' or 'v1' (2 tokens) are not headers and still detected via member lines
        assertEquals(MappingsFormat.TSRG_V1, detect("tsrg a", "\tc d"));
        assertEquals(MappingsFormat.TSRG_V1, detect("tsrg2 a", "\tc d"));
        assertEquals(MappingsFormat.TSRG_V1, detect("v1 a", "\tc d"));
    }

    @Test
    void testTsrgV1WithoutMembers() {
        assertEquals(MappingsFormat.TSRG_V1, detect("a/ b/", "c d"));
        assertEquals(MappingsFormat.TSRG_V1, detect("# comment", "c d", "e f"));
        assertNull(detect("c d", "e f g"));
    }

    @Test
    void testTsrgV1ClassNamedTiny() {
        assertEquals(MappingsFormat.TSRG_V1, detect("tiny a", "\tc d"));
        assertEquals(MappingsFormat.TSRG_V1, detect("tiny a"));
    }

    @Test
    void testPathWithMalformedUtf8(@TempDir final Path dir) throws IOException {
        Path file = dir.resolve("mappings.tsrg");
        Files.write(file, new byte[]{'#', ' ', (byte) 0xE4, '\n', 'a', ' ', 'b', '\n', '\t', 'c', ' ', 'd'});
        assertEquals(MappingsFormat.TSRG_V1, MappingsFormat.detect(file));
    }

    @Test
    void testTsrgV2() {
        assertEquals(MappingsFormat.TSRG_V2, detect("tsrg2 left right", "a b", "\tc d"));
        assertEquals(MappingsFormat.TSRG_V2, detect("tsrg2 a b c", "k1 k2 k3", "\tf fb fc"));
        //A tsrg2 header after a comment line is still detected
        assertEquals(MappingsFormat.TSRG_V2, detect("# comment", "tsrg2 left right", "a b", "\tc d"));
    }

    @Test
    void testTinyV1() {
        assertEquals(MappingsFormat.TINY_V1, detect("v1\ta\tb", "CLASS\tc\td\te"));
        //A header after a comment line is still detected
        assertEquals(MappingsFormat.TINY_V1, detect("# comment", "v1\ta\tb", "CLASS\tc\td\te"));
    }

    @Test
    void testTinyV2() {
        assertEquals(MappingsFormat.TINY_V2, detect("tiny\t2\t0\ta\tb", "c\tc\td\te"));
        //A header after a comment line is still detected
        assertEquals(MappingsFormat.TINY_V2, detect("# comment", "tiny\t2\t0\ta\tb", "c\tc\td\te"));
    }

    @Test
    void testCommentLines() {
        //Comments containing ' -> ' must not be detected as Proguard
        assertEquals(MappingsFormat.SRG, detect("# generated by a -> b", "CL: a b"));
        assertEquals(MappingsFormat.RETROGUARD, detect("# something -> else", ".class_map a b"));
    }

    @Test
    void testInvalidTinyHeader() {
        assertNull(detect("tiny\t3\t0\ta\tb"));
        assertNull(detect("tiny\t1\ta\tb"));
        assertNull(detect("tiny"));
    }

    @Test
    void testEmpty() {
        assertNull(detect());
        assertNull(detect("  ", " "));
    }

    @Test
    void testUnknown() {
        assertNull(detect("a b c"));
    }

    @Test
    void testReader() throws IOException {
        assertEquals(MappingsFormat.TINY_V1, MappingsFormat.detect(new StringReader("v1\ta\tb\nCLASS\tc\td\te")));
    }

    private static MappingsFormat detect(final String... lines) {
        return MappingsFormat.detect(String.join("\n", lines).getBytes(StandardCharsets.UTF_8));
    }

}
